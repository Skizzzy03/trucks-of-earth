local function nearest(lat, lon)
  local k = math.cos(math.rad(lat))
  local best, bd
  for _, g in ipairs(M.TOWNS) do
    for i = 2, #g, 2 do
      local dx, dy = (g[i + 1] - lon) * k, g[i] - lat
      local d = dx * dx + dy * dy
      if not bd or d < bd then best, bd = g, d end
    end
  end
  return best
end

function M.at(lat, lon)
  local g = nearest(lat, lon)
  return g and g[1] or nil
end

-- the state and the country of a place: { code, country, state = nil abroad }
function M.where(lat, lon)
  local g = nearest(lat, lon)
  if not g then return nil end
  if g[1] == 'NL' then return { code = 'NL', country = 'Niederlande' } end
  if g[1] then return { code = 'D', country = 'Deutschland', state = M.STATE[g[1]][1] } end
  return { code = g.cc, country = g.c }
end

return M
